def export_package(target_dir: Path) -> None:
    print(f"Exporting Deliverable 1 static schema package to: {target_dir}")

    # 1. Clean and initialize directory structure (preserving .git if initialized)
    git_backup = None
    if target_dir.exists():
        git_dir = target_dir / ".git"
        if git_dir.exists():
            temp_dir = Path(tempfile.mkdtemp())
            git_backup = temp_dir / ".git"
            shutil.move(str(git_dir), str(git_backup))
        shutil.rmtree(target_dir)
    target_dir.mkdir(parents=True, exist_ok=True)
    if git_backup and git_backup.exists():
        shutil.move(str(git_backup), str(target_dir / ".git"))
        shutil.rmtree(git_backup.parent, ignore_errors=True)

    schema_dest = target_dir / "schema"
    docs_dest = target_dir / "docs"
    github_dest = target_dir / ".github" / "workflows"

    schema_dest.mkdir(parents=True)
    docs_dest.mkdir(parents=True)
    github_dest.mkdir(parents=True)

    # 2. Copy Deliverable 1 Schemas with relative path preservation
    schema_source_root = REPO_ROOT / "src" / "synergy_schema" / "schema"
    schema_files = [
        "deliverable_1_static_schema.yaml",
        "models/urbansim/urbansim_land_use.yaml",
        "models/demos/demos_polaris_mapped_examples.yaml",
        "models/atlas/atlas_fleet_observed_example_v1.yaml",
        "models/polaris/polaris_demand_database_v1.yaml",
        "models/polaris/polaris_skims.yaml",
        "mappings/single_year_handoff.yaml",
    ]

    for rel_path in schema_files:
        src = schema_source_root / rel_path
        dst = schema_dest / rel_path
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        print(f"  Copied schema: {rel_path}")

    # 3. Write Root Files
    (target_dir / "README.md").write_text(STANDALONE_README, encoding="utf-8")
    (target_dir / "LICENSE").write_text(STANDALONE_LICENSE, encoding="utf-8")
    (target_dir / ".gitignore").write_text(STANDALONE_GITIGNORE, encoding="utf-8")
    (target_dir / "pyproject.toml").write_text(STANDALONE_PYPROJECT, encoding="utf-8")
    (target_dir / "zensical.toml").write_text(STANDALONE_ZENSICAL, encoding="utf-8")
    (github_dest / "deploy-pages.yml").write_text(STANDALONE_WORKFLOW, encoding="utf-8")

    print("  Locking dependencies with uv lock...")
    subprocess.run(["uv", "lock"], check=True, cwd=target_dir)

    # 4. Generate Documentation Pages
    (docs_dest / "index.md").write_text(STANDALONE_INDEX_MD, encoding="utf-8")

    # Contract at a glance
    glance_src = REPO_ROOT / "docs" / "cross-model-mappings" / "contract-at-a-glance.md"
    shutil.copy2(glance_src, docs_dest / "contract-at-a-glance.md")

    # Authoritative mapping interface workbook
    resources_dest = docs_dest / "resources"
    resources_dest.mkdir(parents=True, exist_ok=True)
    excel_src = (
        REPO_ROOT / "docs-internal" / "DEMOS_and_ATLAS_to_POLARIS_interface.xlsx"
    )
    if excel_src.exists():
        shutil.copy2(
            excel_src, resources_dest / "DEMOS_and_ATLAS_to_POLARIS_interface.xlsx"
        )
        print(
            "  Copied authoritative interface workbook: DEMOS_and_ATLAS_to_POLARIS_interface.xlsx"
        )

    # JavaScript & CSS assets (MathJax and layout configuration)
    js_dest = docs_dest / "javascripts"
    js_dest.mkdir(parents=True, exist_ok=True)
    (js_dest / "mathjax.js").write_text(STANDALONE_MATHJAX_JS, encoding="utf-8")

    css_dest = docs_dest / "stylesheets"
    css_dest.mkdir(parents=True, exist_ok=True)
    extra_css_src = REPO_ROOT / "docs" / "stylesheets" / "extra.css"
    if extra_css_src.exists():
        shutil.copy2(extra_css_src, css_dest / "extra.css")
    else:
        (css_dest / "extra.css").write_text(STANDALONE_EXTRA_CSS, encoding="utf-8")

    # Deliverable 1 UML
    uml_content = render_deliverable_1_uml()
    (docs_dest / "deliverable_1_uml.md").write_text(uml_content, encoding="utf-8")

    # Database ER Diagram page (Mermaid)
    master_yaml = schema_dest / "deliverable_1_static_schema.yaml"
    generate_interactive_diagram(
        schema_path=master_yaml,
        output_path=docs_dest / "interactive-schema.md",
    )

    # LinkML gen-doc
    gen_doc_dir = docs_dest / "schema"
    gen_doc_dir.mkdir(parents=True, exist_ok=True)
    master_yaml = schema_dest / "deliverable_1_static_schema.yaml"
    print("  Running LinkML gen-doc...")
    subprocess.run(
        [
            "uv",
            "run",
            "gen-doc",
            "--render-imports",
            "--directory",
            str(gen_doc_dir),
            str(master_yaml),
        ],
        check=True,
        cwd=REPO_ROOT,
    )

    # 5. Build static site with Zensical
    print("  Compiling static HTML site with Zensical...")
    site_dest = target_dir / "site"
    if site_dest.exists():
        shutil.rmtree(site_dest, ignore_errors=True)
    subprocess.run(
        ["uv", "run", "zensical", "build"],
        check=True,
        cwd=target_dir,
    )

    # 6. Verify Isolation
    print("  Verifying isolation from FY27 / longitudinal ledger...")
    forbidden_terms = ["duckdb", "core_population", "population_trajectory"]
    for root, dirs, files in os.walk(target_dir):
        dirs[:] = [
            d for d in dirs if d not in {".venv", ".git", ".cache", "__pycache__"}
        ]
        for name in files:
            p = Path(root) / name
            for term in forbidden_terms:
                assert term not in name.lower(), (
                    f"Forbidden file matching '{term}' found: {p}"
                )

    # Verify LinkML SchemaView resolves cleanly in standalone package
    view = SchemaView(str(master_yaml))
    expected_classes = {
        "UrbanSimBlockMarginals",
        "BlockToTazMapping",
        "UrbanSimZonalTotals",
        "DemosPolarisMappedHousehold",
        "DemosPolarisMappedPerson",
        "AtlasHouseholdFleetOutput",
        "AtlasVehicleFleetOutput",
        "PolarisDemandDatabaseHousehold",
        "PolarisDemandDatabasePerson",
        "PolarisDemandDatabaseVehicle",
        "InputNetworkSkims",
        "NextYearNetworkSkims",
        "SingleYearModelHandoffPackage",
        "ModelHandoffChannel",
        "CategoricalCrosswalkRule",
    }
    assert expected_classes.issubset(set(view.all_classes())), (
        "Missing classes in export"
    )

    print("\n✓ Deliverable 1 static schema package exported and verified successfully!")
    print(f"  Destination: {target_dir}")
    print(f"  Pre-compiled site: {target_dir / 'site' / 'index.html'}")


def main() -> None:
    parser = argparse.ArgumentParser(description="Export Deliverable 1 package.")
    parser.add_argument(
        "--target",
        type=Path,
        default=DEFAULT_DIST,
        help="Target export directory path.",
    )
    args = parser.parse_args()
    export_package(args.target)


if __name__ == "__main__":
    main()
