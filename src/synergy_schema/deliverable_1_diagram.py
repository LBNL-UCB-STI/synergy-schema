def main() -> None:
    parser = argparse.ArgumentParser(description="Render Deliverable 1 UML diagrams.")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("docs/cross-model-mappings/deliverable_1_uml.md"),
        help="Path to output markdown file.",
    )
    args = parser.parse_args()
    content = render_deliverable_1_uml()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"Rendered Deliverable 1 UML diagrams to {args.output}")


if __name__ == "__main__":
    main()
